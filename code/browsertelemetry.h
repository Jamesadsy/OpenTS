inline void OpenTS_Browser_Telemetry_Record_Campaign_Phase(int phase)
{
	if (OpenTS_Browser_Telemetry_Value(OPENTS_TELEMETRY_CAMPAIGN_PREPARATION_PHASE) == phase) return;
	OpenTS_Browser_Telemetry_Increment(OPENTS_TELEMETRY_CAMPAIGN_PREPARATION_PHASES);
	OpenTS_Browser_Telemetry_Set(OPENTS_TELEMETRY_CAMPAIGN_PREPARATION_PHASE, phase);
}
